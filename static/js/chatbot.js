'use strict';

// Mission Control: the Project Vulkan chat widget.
// It builds its own markup, so a page only needs chatbot.css and this file.
// Backend: POST /api/chat  { prompt, session_id }  ->  { response: "<html>", sources: [{title, url}] }
(() => {
    if (document.getElementById('vkChat')) return;

    // The planet picture. Defaults to static/images/mars.png (found relative to this script).
    const THIS_SCRIPT = document.currentScript;
    const STATIC_BASE = THIS_SCRIPT && THIS_SCRIPT.src ? THIS_SCRIPT.src.replace(/js\/[^/]*$/, '') : '/static/';
    const MARS_SRC = STATIC_BASE + 'images/mars.png';

    // The chat route, generated by Flask (url_for) so it still works behind a prefix or proxy
    const ENDPOINT = (THIS_SCRIPT && THIS_SCRIPT.dataset.endpoint) || '/api/chat';
    const TIMEOUT_MS = 90000;
    const MAX_SAVED = 40;

    const KEY_HISTORY = 'vulkanChatHistory';
    const KEY_SESSION = 'vulkanChatSession';
    const KEY_OPEN = 'vulkanChatOpen';
    const KEY_NUDGE = 'vulkanChatNudged';

    const SUGGESTIONS = [
        'Why are we going to Mars?',
        'How long is the trip?',
        'Could people really live there?',
        'What is terraforming?',
    ];
    const STATUS_LINES = ['Establishing uplink', 'Scanning the cosmos', 'Decoding transmission'];

    // ── sessionStorage helpers (storage can be blocked, so never let it throw) ──
    const store = {
        get(key) { try { return sessionStorage.getItem(key); } catch (e) { return null; } },
        set(key, value) { try { sessionStorage.setItem(key, value); } catch (e) { /* ignore */ } },
        del(key) { try { sessionStorage.removeItem(key); } catch (e) { /* ignore */ } },
    };

    const newSessionId = () => 'vk_' + Date.now() + '_' + Math.random().toString(36).slice(2, 10);

    let sessionId = store.get(KEY_SESSION) || newSessionId();
    store.set(KEY_SESSION, sessionId);

    let history = [];
    try { history = JSON.parse(store.get(KEY_HISTORY) || '[]'); } catch (e) { history = []; }
    if (!Array.isArray(history)) history = [];

    let busy = false;

    // ── Build the widget ───────────────────────────────────────
    const root = document.createElement('div');
    root.className = 'vk-chat';
    root.id = 'vkChat';
    root.innerHTML = `
        <section class="vk-panel" id="vkPanel" role="dialog" aria-modal="false" aria-labelledby="vkTitle">
            <header class="vk-head">
                <span class="vk-planet vk-avatar" aria-hidden="true"><img src="${MARS_SRC}" alt=""></span>
                <div class="vk-title">
                    <h2 id="vkTitle">Mission Control</h2>
                </div>
                <button class="vk-icon-btn" id="vkNew" type="button" aria-label="Start a new chat" title="New chat">
                    <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M20 11a8 8 0 1 0-2.3 5.7"/><path d="M20 4v7h-7"/></svg>
                </button>
                <button class="vk-icon-btn" id="vkClose" type="button" aria-label="Close chat" title="Close">
                    <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 6l12 12M18 6 6 18"/></svg>
                </button>
            </header>

            <div class="vk-body">
                <div class="vk-log" id="vkLog" role="log" aria-live="polite" aria-relevant="additions"></div>
            </div>

            <form class="vk-form" id="vkForm" autocomplete="off">
                <textarea class="vk-input" id="vkInput" rows="1" maxlength="800"
                    placeholder="Ask about Mars, the crew, the rocket…" aria-label="Your message"></textarea>
                <button class="vk-send" id="vkSend" type="submit" aria-label="Send message" disabled>
                    <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M3.4 20.4 21 12 3.4 3.6l.1 6.5L15 12 3.5 13.9z"/></svg>
                </button>
            </form>
            <p class="vk-foot">AI can make mistakes, so double-check important facts.</p>
        </section>

        <button class="vk-nudge" id="vkNudge" type="button" tabindex="-1">
            Questions about the mission? <b>Ask Mission Control.</b>
        </button>

        <button class="vk-launcher" id="vkLauncher" type="button" aria-expanded="false"
            aria-controls="vkPanel" aria-label="Open Mission Control chat">
            <span class="vk-planet" aria-hidden="true"><img src="${MARS_SRC}" alt=""></span>
            <span class="vk-badge" aria-hidden="true">
                <svg class="vk-i-chat" viewBox="0 0 24 24">
                    <path d="M5 5h14a2 2 0 0 1 2 2v8a2 2 0 0 1-2 2h-6.5L8 20.5V17H5a2 2 0 0 1-2-2V7a2 2 0 0 1 2-2z"/>
                    <path d="M12 7.9l.85 2.05 2.05.85-2.05.85L12 13.7l-.85-2.05-2.05-.85 2.05-.85z"/>
                </svg>
                <svg class="vk-i-close" viewBox="0 0 24 24"><path d="M6 6l12 12M18 6 6 18"/></svg>
            </span>
        </button>
    `;
    document.body.appendChild(root);

    const $ = (id) => root.querySelector('#' + id);
    const launcher = $('vkLauncher');
    const panel = $('vkPanel');
    const nudge = $('vkNudge');
    const log = $('vkLog');
    const form = $('vkForm');
    const input = $('vkInput');
    const sendBtn = $('vkSend');

    // If mars.png is missing or misnamed, fall back to a painted Mars instead of a broken image
    root.querySelectorAll('.vk-planet img').forEach((img) => {
        img.addEventListener('error', () => {
            img.parentElement.classList.add('is-fallback');
            img.remove();
        });
    });

    // ── Messages ───────────────────────────────────────────────
    function scrollToBottom() { log.scrollTop = log.scrollHeight; }

    // For a long answer, show where it STARTS instead of dumping the reader at the end
    function scrollToMessage(el) { log.scrollTop = Math.max(0, el.offsetTop - 12); }

    function makeSources(sources) {
        const list = (sources || []).filter((s) => s && /^https?:\/\//i.test(s.url));
        if (!list.length) return null;

        const details = document.createElement('details');
        details.className = 'vk-sources';
        const summary = document.createElement('summary');
        summary.textContent = list.length === 1 ? '1 source' : list.length + ' sources';
        details.appendChild(summary);

        const ul = document.createElement('ul');
        list.forEach((s) => {
            const li = document.createElement('li');
            const a = document.createElement('a');
            a.href = s.url;
            a.textContent = s.title || s.url;
            a.target = '_blank';
            a.rel = 'noopener noreferrer';
            li.appendChild(a);
            ul.appendChild(li);
        });
        details.appendChild(ul);
        return details;
    }

    // role: 'user' | 'bot'.  content: { text } (plain) or { html, sources } (from the server)
    function addMessage(role, content) {
        const el = document.createElement('div');
        el.className = 'vk-msg ' + role;

        if (content.html !== undefined) {
            el.innerHTML = content.html;               // server escapes model output before rendering
            el.querySelectorAll('a').forEach((a) => {
                a.target = '_blank';
                a.rel = 'noopener noreferrer';
            });
            const sources = makeSources(content.sources);
            if (sources) el.appendChild(sources);
        } else {
            el.textContent = content.text;
        }

        log.appendChild(el);
        return el;
    }

    function saveHistory() {
        store.set(KEY_HISTORY, JSON.stringify(history.slice(-MAX_SAVED)));
    }

    function renderWelcome(withChips) {
        addMessage('bot', {
            html: '<p>Hi, I\'m <strong>Mission Control</strong> 🚀 Ask me anything about Mars, our rocket, or the crew heading there.</p>',
        });

        if (!withChips) return;
        const chips = document.createElement('div');
        chips.className = 'vk-chips';
        chips.id = 'vkChips';
        SUGGESTIONS.forEach((q) => {
            const b = document.createElement('button');
            b.type = 'button';
            b.className = 'vk-chip';
            b.textContent = q;
            b.addEventListener('click', () => send(q));
            chips.appendChild(b);
        });
        log.appendChild(chips);
    }

    function renderAll() {
        log.innerHTML = '';
        renderWelcome(history.length === 0);
        history.forEach((m) => addMessage(m.r === 'u' ? 'user' : 'bot', m.r === 'u' ? { text: m.t } : { html: m.h, sources: m.s }));
        scrollToBottom();
    }

    // ── Thinking indicator ─────────────────────────────────────
    function showTyping() {
        const el = document.createElement('div');
        el.className = 'vk-msg bot vk-typing';
        el.innerHTML = '<span class="vk-dots" aria-hidden="true"><i></i><i></i><i></i></span><span class="vk-typing-text"></span>';
        const label = el.querySelector('.vk-typing-text');

        let i = 0;
        label.textContent = STATUS_LINES[0];
        const timer = setInterval(() => {
            i = (i + 1) % STATUS_LINES.length;
            label.textContent = STATUS_LINES[i];
        }, 1800);

        log.appendChild(el);
        scrollToBottom();
        return () => { clearInterval(timer); el.remove(); };
    }

    // ── Sending ────────────────────────────────────────────────
    function setBusy(value) {
        busy = value;
        updateSendState();
    }

    function updateSendState() {
        sendBtn.disabled = busy || !input.value.trim();
    }

    function autosize() {
        input.style.height = 'auto';
        input.style.height = Math.min(input.scrollHeight, 112) + 'px';
    }

    async function send(raw) {
        const text = (raw || '').trim();
        if (!text || busy) return;

        const chips = $('vkChips');
        if (chips) chips.remove();

        addMessage('user', { text });
        history.push({ r: 'u', t: text });
        input.value = '';
        autosize();
        setBusy(true);
        scrollToBottom();

        const stopTyping = showTyping();
        const controller = new AbortController();
        const timeout = setTimeout(() => controller.abort(), TIMEOUT_MS);

        let reply;
        try {
            const res = await fetch(ENDPOINT, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ prompt: text, session_id: sessionId }),
                signal: controller.signal,
            });
            // The server sends a friendly message even on errors, so read the body either way
            const data = await res.json().catch(() => ({}));
            reply = data.response
                ? { html: data.response, sources: res.ok ? (data.sources || []) : [] }
                : { html: '<p>That transmission didn\'t come through. Please try again.</p>' };
        } catch (err) {
            reply = {
                html: err.name === 'AbortError'
                    ? '<p>That took too long, so I lost the signal. Please try again.</p>'
                    : '<p>I can\'t reach Mission Control right now. Check your connection and try again.</p>',
            };
        } finally {
            clearTimeout(timeout);
            stopTyping();
        }

        const el = addMessage('bot', reply);
        history.push({ r: 'b', h: reply.html, s: reply.sources });
        saveHistory();
        setBusy(false);
        scrollToMessage(el);
        if (isOpen() && window.matchMedia('(hover: hover)').matches) input.focus();
    }

    // ── Open / close ───────────────────────────────────────────
    const isOpen = () => root.classList.contains('is-open');

    function hideNudge() {
        nudge.classList.remove('show');
        nudge.tabIndex = -1;
    }

    function setOpen(open, { focus = true } = {}) {
        root.classList.toggle('is-open', open);
        launcher.setAttribute('aria-expanded', String(open));
        launcher.setAttribute('aria-label', open ? 'Close Mission Control chat' : 'Open Mission Control chat');
        store.set(KEY_OPEN, open ? '1' : '0');

        if (open) {
            hideNudge();
            store.set(KEY_NUDGE, '1');
            scrollToBottom();
            // Only auto-focus where it won't pop a phone keyboard over the answer
            if (focus && window.matchMedia('(hover: hover)').matches) input.focus({ preventScroll: true });
        } else if (focus) {
            launcher.focus({ preventScroll: true });
        }
    }

    launcher.addEventListener('click', () => setOpen(!isOpen()));
    $('vkClose').addEventListener('click', () => setOpen(false));
    nudge.addEventListener('click', () => setOpen(true));

    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && isOpen()) setOpen(false);
    });

    // ── New chat ───────────────────────────────────────────────
    $('vkNew').addEventListener('click', () => {
        if (busy) return;
        sessionId = newSessionId();
        store.set(KEY_SESSION, sessionId);
        history = [];
        store.del(KEY_HISTORY);
        renderAll();
        input.focus({ preventScroll: true });
    });

    // ── Composer ───────────────────────────────────────────────
    form.addEventListener('submit', (e) => {
        e.preventDefault();
        send(input.value);
    });

    input.addEventListener('input', () => {
        autosize();
        updateSendState();
    });

    input.addEventListener('keydown', (e) => {
        // Enter sends, Shift+Enter makes a new line (and never send mid-IME-composition)
        if (e.key === 'Enter' && !e.shiftKey && !e.isComposing) {
            e.preventDefault();
            send(input.value);
        }
    });

    // ── Start up ───────────────────────────────────────────────
    renderAll();

    if (store.get(KEY_OPEN) === '1') {
        setOpen(true, { focus: false });
    } else if (store.get(KEY_NUDGE) !== '1') {
        // A single, polite invitation per browser session
        setTimeout(() => {
            if (isOpen()) return;
            nudge.classList.add('show');
            nudge.tabIndex = 0;
            setTimeout(hideNudge, 9000);
        }, 4000);
        store.set(KEY_NUDGE, '1');
    }
})();